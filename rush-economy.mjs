/** Read-only validation for pairing an issued profile with its engine checkpoint. */
export function validProfile(p) {
  if (!object(p) || own(p, 'version') !== C.version) return false;
  if(Object.hasOwn(p,'doorCoins')&&!validDoorCoins(p.doorCoins,p.openRooms))return false;
  if(Object.hasOwn(p,'firstSteps')&&!validFirstSteps(own(p,'firstSteps')))return false;
  if(Object.hasOwn(p,'staffAutomation')&&!validStaffPlan(own(p,'staffAutomation')))return false;
  if (Object.hasOwn(p,'rewards') && !validRewards(own(p,'rewards'))) return false;
  if(Object.hasOwn(p,'location')&&!validLocation(own(p,'location')))return false;
  if (Object.hasOwn(p,'construction') && !validConstruction(own(p,'construction'),own(p,'openRooms'))) return false;
  const ranges = { bank: [0, MAX], openRooms: [1, C.maxRooms],
    staffCount: [C.startingStaff, C.maxStaff], serviceLevel: [0, C.maxServiceLevel],
    nextShift: [1, MAX], lastSettledShift: [0, MAX - 1],
    shiftsCompleted: [0, MAX], guestsCompleted: [0, MAX] };
  for (const [key, [min, max]] of Object.entries(ranges)) {
    const value = own(p, key);
    if (!integer(value) || value < min || value > max) return false;
  }
  const tiers = own(p, 'roomTiers'), facilities = own(p, 'facilities');
  if (!Array.isArray(tiers) || tiers.length !== C.maxRooms ||
    Array.from({ length: C.maxRooms }, (_, i) => arrayItem(tiers, i)).some((tier, i) =>
      !integer(tier) || tier > C.maxRoomTier || (i >= p.openRooms && tier !== 0))) return false;
  for (const key of facilityKinds) if (![0, 1].includes(own(facilities, key))) return false;
  if (facilities.salon > facilities.restaurant || facilities.spa > facilities.salon ||
    !integer(own(p, 'chefLevel')) || p.chefLevel > C.maxChefLevel || p.chefLevel > facilities.restaurant) return false;
  const restaurantTier = own(p, 'restaurantTier'), selected = cuisineById(own(p, 'selectedCuisine'));
  if (!integer(restaurantTier) || restaurantTier > C.maxRestaurantTier ||
    (facilities.restaurant ? restaurantTier < 1 || !selected || selected.tier > restaurantTier
      : restaurantTier !== 0 || own(p, 'selectedCuisine') !== null)) return false;
  const leisure = own(p, 'leisure'), performerLevel = own(p, 'performerLevel');
  if (!object(leisure) || Object.keys(leisure).length !== LEISURE_IDS.length ||
    LEISURE_IDS.some(id => ![0, 1].includes(own(leisure, id))) || ![0, 1].includes(performerLevel) ||
    (leisure.lounge && (restaurantTier !== 6 || p.shiftsCompleted < 7)) ||
    (leisure.theater && (!leisure.lounge || p.shiftsCompleted < 9)) ||
    (performerLevel && (!leisure.theater || p.shiftsCompleted < 10))) return false;
  const reviews = own(p, 'recentReviews');
  if (!Array.isArray(reviews) || reviews.length > C.maxReviews ||
    cleanReviews(reviews, p.lastSettledShift).length !== reviews.length) return false;
  if (p.nextShift <= p.lastSettledShift) return false;
  if(own(p,'reputation')!==undefined && (!validReputation(p.reputation)||p.reputation.lastAppliedShift>p.lastSettledShift))return false;
  const active = own(p, 'activeShift');
  if (active === null) return true;
  if(hasField(active,'roomDoorXs')&&(!validBinding(active)||!validRoomDoorXs(own(active,'roomDoorXs'))))return false;
  if(Object.hasOwn(active,'coinPickupRules')||Object.hasOwn(active,'pickupCarry')){if(active.coinPickupRules!==1||!validBinding(active)||!validDoorCoins(active.pickupCarry,p.openRooms)||JSON.stringify(active.pickupCarry)!==JSON.stringify(p.doorCoins))return false;}
  else if(Object.hasOwn(p,'doorCoins'))return false;
  if(own(active,'firstStepsRules')!==undefined&&(!validFirstSteps(p.firstSteps)||![1,2].includes(own(active,'firstStepsRules'))||active.motionRules!==3||active.motionMode!=='relaxed'))return false;
  if(own(active,'staffPlan')!==undefined&&(!validStaffPlan(active.staffPlan)||JSON.stringify(active.staffPlan)!==JSON.stringify(p.staffAutomation)))return false;
  if(own(active,'reputationPlan')!==undefined && (!p.reputation||!validReputationPlan(active.reputationPlan)||JSON.stringify(active.reputationPlan)!==JSON.stringify(reputationPlan(p,active.motionMode))))return false;
  const n = ordinal(own(active, 'id'));
  return !!n && own(active, 'ordinal') === n && n > p.lastSettledShift && n < p.nextShift &&
    own(active, 'startingBank') === p.bank && (!hasBinding(active) || validBinding(active));
}

/** Lock purchases for this shift. Persist this profile and its engine state together. */
export function beginShift(profile, options) {
  if (!validProfile(profile)) return fail('Hotel save is invalid.', 'invalid-profile');
  if (profile.activeShift) return fail('Finish or resume the current shift.', 'active-shift');
  const bound = options !== undefined;
  if(hasField(options,'roomDoorXs')&&(!bound||!validRoomDoorXs(own(options,'roomDoorXs'))))return fail('Invalid first-floor doors.','invalid-room-doors');
  const roomDoors=hasField(options,'roomDoorXs')?{roomDoorXs:copyRoomDoorXs(own(options,'roomDoorXs'))}:{};
  if(options&&Object.hasOwn(options,'coinPickupRules')&&options.coinPickupRules!==1)return fail('Unknown door-coin policy.','invalid-coin-policy');
  if(!bound&&Object.hasOwn(profile,'doorCoins'))return fail('Door coins require a bound shift.','invalid-coin-policy');
  const doorCoins=bound&&(options?.coinPickupRules===1||Object.hasOwn(profile,'doorCoins'));
  if (bound && (!validMotionRule(own(options, 'motionRules')) || !['rush', 'relaxed'].includes(own(options, 'motionMode')) ||
    hasField(options, 'engineVersion') && own(options, 'engineVersion') !== 7))
    return fail('Choose a valid motion shift policy.', 'invalid-motion-policy');
  if (profile.nextShift >= MAX) return fail('No more shift IDs are available.', 'id-exhausted');
  const firstRule=bound&&own(options,'motionRules')===3&&own(options,'motionMode')==='relaxed'?firstStepsRule(profile):0;
  const newspaper=own(options,'reputationRules')===1&&!firstRule;
  if(newspaper&&own(options,'motionRules')!==3)return fail('Newspaper rules require a new calm-era session.','invalid-reputation-policy');
  if(newspaper&&!profile.reputation)profile.reputation=freshReputation();
  const plan=newspaper?reputationPlan(profile,own(options,'motionMode')):null;
  const staffPlan=bound&&own(options,'motionRules')===3?staffPlanForProfile(profile):null;
  if(staffPlan)profile.staffAutomation=copyStaffPlan(staffPlan);
  if(doorCoins&&!profile.doorCoins)profile.doorCoins=freshDoorCoins();
  const pickupBinding=doorCoins?{coinPickupRules:1,pickupCarry:copyDoorCoins(profile.doorCoins)}:{};
  const n = profile.nextShift++;
  const shiftId = `shift-${n}`;
  const binding = bound ? { engineVersion: 7, motionRules: own(options, 'motionRules'), motionMode: own(options, 'motionMode') } : null;
  profile.activeShift = { id: shiftId, ordinal: n, startingBank: profile.bank, ...pickupBinding, ...roomDoors, ...(staffPlan?{staffPlan:copyStaffPlan(staffPlan)}:{}), ...(binding ?? {}),...(firstRule?{firstStepsRules:firstRule}:{}),...(plan?{reputationPlan:plan}:{}) };
  return { ok: true, shiftId, options: { startingMoney: profile.bank, openRooms: profile.openRooms, ...pickupBinding, ...(roomDoors.roomDoorXs?{roomDoorXs:copyRoomDoorXs(roomDoors.roomDoorXs)}:{}),
    staffCount: profile.staffCount, serviceLevel: profile.serviceLevel,
    ...(staffPlan?{staffPlan:copyStaffPlan(staffPlan)}:{}),
    ...(profile.construction ? {constructionRules:1,roomSlots:[...profile.construction.slots]} : {}),
    roomTiers: [...profile.roomTiers], facilities: { ...profile.facilities }, chefLevel: profile.chefLevel,
    restaurantCuisine: profile.selectedCuisine, leisureRules: 1, leisure: { ...profile.leisure },
    performerLevel: profile.performerLevel, completedShifts: profile.shiftsCompleted,
    ...(bound ? { shiftId, ...motionOptions(binding.motionMode, binding.motionRules), sessionRules: 1, contentRules: 1, cuisineRules: 1,
      visitSeed: n, ...firstStepsOptions(firstRule), ...(plan?{reputationPlan:plan,...(plan.booking?{arrivalSchedule:[...motionOptions(binding.motionMode,binding.motionRules).arrivalSchedule,motionOptions(binding.motionMode,binding.motionRules).arrivalSchedule.at(-1)+30]}:{})}:{}) } : {}) } };
}

function boundIdentity(raw, active, summary=false) {
  if (own(raw, 'version') !== 7 || own(raw, 'shiftId') !== active.id) return false;
  const config = own(raw, 'config'), policy = hasField(raw, 'config') ? config : raw;
  if(!summary&&JSON.stringify(own(active,'roomDoorXs'))!==JSON.stringify(own(config,'roomDoorXs')))return false;
  if(!summary&&(active.coinPickupRules!==own(config,'coinPickupRules')||JSON.stringify(active.pickupCarry)!==JSON.stringify(own(config,'pickupCarry'))))return false;
  if(!summary&&own(active,'firstStepsRules')!==own(config,'firstStepsRules'))return false;
  if(!summary&&JSON.stringify(own(active,'staffPlan'))!==JSON.stringify(own(config,'staffPlan')))return false;
  if(!summary&&JSON.stringify(own(active,'reputationPlan'))!==JSON.stringify(own(config,'reputationPlan')))return false;
  if(!summary&&own(active,'reputationPlan') && !validateReputationState(raw))return false;
  if (own(policy, 'motionRules') !== active.motionRules || own(policy, 'motionMode') !== active.motionMode) return false;
  // A state normally stores policy in config only; contradictory duplicate tags
  // must not become a second, caller-controlled choice of receipt policy.
  if (hasField(raw, 'engineVersion') && own(raw, 'engineVersion') !== active.engineVersion) return false;
  return ['motionRules', 'motionMode'].every(key => !hasField(raw, key) || own(raw, key) === active[key]);
}

function inspectionReceipt(raw, ledger, required) {
  const directBonus = own(raw, 'inspectionBonus'), stateBonus = own(own(raw, 'inspection'), 'bonus');
  if (directBonus !== undefined && stateBonus !== undefined && directBonus !== stateBonus ||
    required && directBonus === undefined && stateBonus === undefined)
    return fail('The inspection receipt is invalid.', 'invalid-ledger');
  const bonus = directBonus ?? stateBonus ?? 0;
  if (![0, 10].includes(bonus) || bonus > ledger.earnings || bonus > ledger.money)
    return fail('The inspection receipt is invalid.', 'invalid-ledger');
  return { ok: true, bonus };
}

function boundLedger(raw, active, ledger, abandoned) {
  if (!boundIdentity(raw, active))
    return fail('This result does not match the issued motion shift.', 'shift-binding-mismatch');
  if (own(raw, 'startingMoney') !== active.startingBank || !integer(own(raw, 'tips')))
    return fail('The bound shift ledger is incomplete.', 'invalid-ledger');
  if(active.coinPickupRules===1){
    if(!hasCoinPickups(raw)||!validCoinState(raw)||JSON.stringify(coinCash(raw))!==JSON.stringify(ledger.coinCash))return fail('Door receipts do not match this shift.','invalid-ledger');
  }else if(own(raw,'coinCash')!==undefined||own(own(raw,'result'),'coinCash')!==undefined)return fail('Unbound door receipts.','invalid-ledger');
  const inspection = inspectionReceipt(raw, ledger, true);
  if (!inspection.ok) return inspection;
  if (ledger.tips > ledger.earnings - inspection.bonus)
    return fail('Tips cannot include the inspection receipt.', 'invalid-ledger');
  const result = own(raw, 'result');
  if (result !== undefined && result !== null) {
    if (!boundIdentity(result, active,true))
      return fail('The terminal result does not match its motion shift.', 'shift-binding-mismatch');
    const terminal = readLedger(result, active.startingBank, false);
    if (!terminal.ok) return terminal;
    if (own(result, 'startingMoney') !== active.startingBank || !integer(own(result, 'tips')) ||
      ['money', 'earnings', 'costs', 'stolen', 'tips', 'completed', 'missed'].some(key => terminal[key] !== ledger[key]) || JSON.stringify(terminal.coinCash)!==JSON.stringify(ledger.coinCash) ||
      (!abandoned && terminal.status !== ledger.status) ||
      !['won', 'lost'].includes(own(raw, 'status')) || terminal.status !== own(raw, 'status'))
      return fail('The terminal ledger does not match its motion shift.', 'invalid-ledger');
    const terminalInspection = inspectionReceipt(result, terminal, true);
    if (!terminalInspection.ok || terminalInspection.bonus !== inspection.bonus)
      return fail('The inspection receipt is invalid.', 'invalid-ledger');
  }
  return inspection;
}

function readLedger(raw, startingBank, abandoned) {
  if (!object(raw)) return fail('The shift result is missing.', 'invalid-result');
  const rawStatus = own(raw, 'status'), won = own(raw, 'won');
  const status = rawStatus === undefined && typeof won === 'boolean' ? (won ? 'won' : 'lost') : rawStatus;
  if (abandoned ? !['playing', 'paused', 'won', 'lost'].includes(status) : !['won', 'lost'].includes(status))
    return fail('The shift has not finished.', 'not-terminal');
  const startingMoney = own(raw, 'startingMoney');
  if (startingMoney !== undefined && startingMoney !== startingBank)
    return fail('This result belongs to another starting balance.', 'starting-balance-mismatch');
  const ledger = {};
  for (const key of ['money', 'earnings', 'costs', 'stolen', 'completed']) {
    const value = own(raw, key);
    if (!integer(value)) return fail('The shift ledger is invalid.', 'invalid-ledger');
    ledger[key] = value;
  }
  for (const key of ['tips', 'missed']) {
    const value = own(raw, key);
    if (value !== undefined && !integer(value)) return fail('The shift ledger is invalid.', 'invalid-ledger');
    ledger[key] = value ?? 0;
  }
  const cash=own(raw,'coinCash')??(hasCoinPickups(raw)?coinCash(raw):undefined);
  if(cash!==undefined){if(!validCoinCash(cash))return fail('The cash receipt is invalid.','invalid-ledger');ledger.coinCash={...cash};}
  const delta=BigInt(cash?.carried||0)-BigInt(cash?.held||0);
  const net = Number(BigInt(ledger.earnings)-BigInt(ledger.costs)-BigInt(ledger.stolen)+delta);
  // Use BigInt for the check so huge/tampered values cannot exploit rounding.
  const exact = BigInt(startingBank) + BigInt(ledger.earnings) - BigInt(ledger.costs) - BigInt(ledger.stolen) + delta;
  if (!Number.isSafeInteger(net) || exact < 0n || exact > BigInt(MAX) || BigInt(ledger.money) !== exact ||
    ledger.tips > ledger.earnings)
    return fail('The shift ledger does not balance.', 'unbalanced-ledger');
  return { ok: true, ...ledger, net, status: abandoned ? 'abandoned' : status };
}

function finishShift(profile, shiftId, result, abandoned) {
  if (!validProfile(profile)) return fail('Hotel save is invalid.', 'invalid-profile');
  const active = profile.activeShift;
  if (!active || shiftId !== active.id || ordinal(shiftId) <= profile.lastSettledShift)
    return fail('This shift was already collected or is out of date.', 'stale-shift');
  const ledger = readLedger(result, active.startingBank, abandoned);
  if (!ledger.ok) return ledger;
  const bound = hasBinding(active), checkedBinding = bound ? boundLedger(result, active, ledger, abandoned) : null;
  if (bound && !checkedBinding.ok) return checkedBinding;
  if(abandoned&&active.coinPickupRules===1&&result.guests.some(g=>g.paid&&!g.departed))return fail('Finish the guest checkout before leaving.','finish-checkout');
  if (abandoned) {
    const inspection = checkedBinding ?? inspectionReceipt(result, ledger, false);
    if (!inspection.ok) return inspection;
    const { bonus } = inspection;
    // Even abandoning an already-finished snapshot cannot preserve its bonus
    // while retaining the same completed-shift inspection milestone.
    ledger.money -= bonus; ledger.earnings -= bonus; ledger.net -= bonus;
  }
  if (!Number.isSafeInteger(profile.guestsCompleted + ledger.completed) ||
    (!abandoned && profile.shiftsCompleted >= MAX))
    return fail('Hotel totals are too large.', 'total-overflow');
  const summary = { shiftId, status: ledger.status, won: ledger.status === 'won',
    startingBank: active.startingBank, bank: ledger.money, earnings: ledger.earnings,
    costs: ledger.costs, stolen: ledger.stolen, tips: ledger.tips, net: ledger.net,
    completed: ledger.completed, missed: ledger.missed, ...(ledger.coinCash?{coinCash:{...ledger.coinCash}}:{}) };
  const reviews = shiftReviews(result, shiftId, active.ordinal);
  settleReputation(profile,result,shiftId,abandoned);
  settleStaffLearning(profile,result);
  profile.bank = ledger.money;
  if(active.coinPickupRules===1)profile.doorCoins=pendingDoorCoins(result);
  profile.lastSettledShift = active.ordinal;
  profile.activeShift = null;
  profile.shiftsCompleted += abandoned ? 0 : 1;
  profile.guestsCompleted += ledger.completed;
  profile.lastResult = summary;
  profile.recentReviews = [...profile.recentReviews, ...reviews].slice(-C.maxReviews);
  return { ok: true, bank: profile.bank, net: ledger.net, result: { ...summary } };
}

/** Accept a terminal engine snapshot or its result object. Tips already belong to earnings. */
export function settleShift(profile, shiftId, result) {
  return finishShift(profile, shiftId, result, false);
}

/** Keep only real paid earnings and committed costs/theft; no restart refund or bonus. */
export function abandonShift(profile, shiftId, state) {
  return finishShift(profile, shiftId, state, true);
}

/** Read-only shop descriptor, or all descriptors when kind is omitted. */
export function canPurchase(profile, kind) {
  if (kind === undefined) return kinds.map(value => canPurchase(profile, value));
  if (['leisure-lounge-1', 'leisure-theater-1', 'performer-1'].includes(kind)) return leisureOffer(profile, kind);
  if (typeof kind === 'string' && /^cuisine-[2-6]$/.test(kind)) return cuisineOffer(profile, kind);
  if (typeof kind === 'string' && /^(room-tier-[1-6]-[12]|facility-(restaurant|salon|spa)-1|chef-1)$/.test(kind))
    return contentOffer(profile, kind);
  const requestedId = typeof kind === 'string' && /^(room-[23456]|staff-3|service-1)$/.test(kind) ? kind : null;
  if (requestedId) kind = requestedId.split('-')[0];
  if (!kinds.includes(kind)) return { ...fail('Unknown hotel upgrade.', 'unknown-purchase'),
    kind, label: '', price: null, enabled: false, maxed: false };
  if (!validProfile(profile)) return { ...fail('Hotel save is invalid.', 'invalid-profile'),
    kind, label: '', price: null, enabled: false, maxed: false };
  const count = kind === 'room' ? profile.openRooms : kind === 'staff' ? profile.staffCount : profile.serviceLevel;
  const max = kind === 'room' ? C.maxRooms : kind === 'staff' ? C.maxStaff : C.maxServiceLevel;
  const maxed = count >= max;
  const id = `${kind}-${Math.min(max, count + 1)}`;
  const stale = requestedId !== null && requestedId !== id;
  const price = maxed ? null : kind === 'room' ? C.roomPrices[count + 1] : kind === 'staff' ? staffHirePrice(profile,C.staffPrice) : C.servicePrice;
  const label = kind === 'room' ? (maxed ? 'All rooms open' : count === 3 ? 'Open floor 2' : `Open room ${count + 1}`) :
    kind === 'staff' ? (maxed ? 'Rue hired · automatic learned duties' : 'Hire Rue · learns one duty at a time') : (maxed ? 'Service upgraded' : 'Faster service');
  const reason = profile.activeShift ? 'Finish the shift first.' : kind==='room' && profile.construction?.project ? 'Your builders are already at work.' : stale ? 'This offer is out of date.' : maxed ? 'Already fully upgraded.' :
    kind==='staff'&&staffHireGate(profile)?staffHireGate(profile):
    profile.bank < price ? `Need ${price - profile.bank} more coins.` : '';
  return { id, kind, label, price, count, max, maxed, ok: !reason, enabled: !reason, reason, message: reason,
    ...(stale ? { code: 'stale-offer' } : {}) };
}

/** Re-check affordability and limits at click time; never trust a cached shop descriptor. */
export function purchase(profile, kind) {
  if (kind === undefined) return fail('Choose a hotel upgrade.', 'unknown-purchase');
  const offer = canPurchase(profile, kind);
  if (!offer.ok) return offer;
  profile.bank -= offer.price;
  if (offer.kind === 'leisure') {
    profile.leisure[offer.venueId] = 1;
    return { ...offer, bank: profile.bank, value: 1 };
  }
  if (offer.kind === 'performer') {
    profile.performerLevel = 1;
    return { ...offer, bank: profile.bank, value: 1 };
  }
  if (offer.kind === 'room-tier') {
    profile.roomTiers[offer.roomIndex] = offer.nextTier;
    return { ...offer, bank: profile.bank, value: offer.nextTier };
  }
  if (offer.kind === 'facility') {
    profile.facilities[offer.facility] = 1;
    if (offer.facility === 'restaurant') { profile.restaurantTier = 1; profile.selectedCuisine = 'ramen'; }
    return { ...offer, bank: profile.bank, value: 1 };
  }
  if (offer.kind === 'cuisine') {
    profile.restaurantTier = offer.nextTier;
    profile.selectedCuisine = offer.cuisineId;
    return { ...offer, bank: profile.bank, value: offer.nextTier };
  }
  if (offer.kind === 'chef') {
    profile.chefLevel = 1;
    return { ...offer, bank: profile.bank, value: 1 };
  }
  const key = offer.kind === 'room' ? 'openRooms' : offer.kind === 'staff' ? 'staffCount' : 'serviceLevel';
  profile[key] += 1;
  if(offer.kind==='staff'){const plan=staffPlanForProfile(profile);profile.staffAutomation={...plan,enabled:true,learned:[...new Set(['welcome',...plan.learned])].filter(k=>staffDutyOpen(k,profile.shiftsCompleted))};}
  return { ...offer, bank: profile.bank, value: profile[key] };
}

/** A displayed tier token can be spent once, never upgraded to a later offer
 * on a repeated click. This is independent of which owned menu is selected. */
function cuisineOffer(profile, requestedId) {
  if (!validProfile(profile)) return { ...fail('Hotel save is invalid.', 'invalid-profile'),
    id: requestedId, kind: 'cuisine', label: '', price: null, enabled: false, maxed: false };
  const count = profile.restaurantTier, maxed = count >= C.maxRestaurantTier;
  const nextTier = Math.min(C.maxRestaurantTier, Math.max(2, count + 1));
  const cuisine = CUISINES[nextTier - 1], id = `cuisine-${nextTier}`, stale = requestedId !== id;
  const gate = !count ? 'Open the ramen restaurant first.' : profile.shiftsCompleted < cuisine.requiredShifts
    ? `Complete ${cuisine.requiredShifts} shifts to unlock.` : '';
  const reason = profile.activeShift ? 'Finish the shift first.' : stale ? 'This offer is out of date.' :
    maxed ? 'Every restaurant cuisine is unlocked.' : gate ||
    (profile.bank < cuisine.price ? `Need ${cuisine.price - profile.bank} more coins.` : '');
  const code = profile.activeShift ? 'active-shift' : stale ? 'stale-offer' : maxed ? 'maxed' :
    gate ? 'locked' : reason ? 'insufficient-funds' : null;
  return { id, kind: 'cuisine', cuisineId: cuisine.id, label: maxed ? 'Every cuisine unlocked' : `Open ${cuisine.name.toLowerCase()}`,
    price: maxed ? null : cuisine.price, count, nextTier, max: C.maxRestaurantTier, maxed,
    prerequisite: 'restaurant', requiredShifts: cuisine.requiredShifts,
    ok: !reason, enabled: !reason, reason, message: reason, ...(code ? { code } : {}) };
}

/** Menu choices never spend coins, erase owned tiers, or rewrite an active shift. */
export function selectCuisine(profile, id) {
  if (!validProfile(profile)) return fail('Hotel save is invalid.', 'invalid-profile');
  if (profile.activeShift) return fail('Finish the shift first.', 'active-shift');
  const cuisine = cuisineById(id);
  if (!cuisine) return fail('Choose a known cuisine.', 'unknown-cuisine');
  if (cuisine.tier > profile.restaurantTier) return fail('Unlock this cuisine first.', 'locked');
  profile.selectedCuisine = cuisine.id;
  return { ok: true, cuisineId: cuisine.id, selectedCuisine: cuisine.id, restaurantTier: profile.restaurantTier };
}

function contentOffer(profile, requestedId) {
  if (!validProfile(profile)) return { ...fail('Hotel save is invalid.', 'invalid-profile'),
    id: requestedId, label: '', price: null, enabled: false, maxed: false };
  let descriptor, gate = '', stale = false;
  const roomMatch = /^room-tier-([1-6])-([12])$/.exec(requestedId);
  if (roomMatch) {
    const roomNumber = Number(roomMatch[1]), roomIndex = roomNumber - 1, tier = profile.roomTiers[roomIndex];
    const maxed = tier === C.maxRoomTier, nextTier = Math.min(C.maxRoomTier, tier + 1);
    const id = `room-tier-${roomNumber}-${nextTier}`, tierName = nextTier === 1 ? 'Luxury' : 'Family';
    stale = requestedId !== id;
    gate = roomIndex >= profile.openRooms ? 'Open this room first.' : '';
    descriptor = { id, kind: 'room-tier', roomId: `room-${roomNumber}`, roomIndex, tier, nextTier,
      label: maxed ? `Room ${roomNumber}: Family` : `Room ${roomNumber}: ${tierName}`,
      price: maxed ? null : C.roomTierPrices[nextTier], count: tier, max: C.maxRoomTier, maxed };
  } else if (requestedId.startsWith('facility-')) {
    const facility = requestedId.split('-')[1], count = profile.facilities[facility];
    const names = { restaurant: 'ramen restaurant', salon: 'salon', spa: 'massage spa' };
    const prerequisite = { salon: 'restaurant', spa: 'salon' }[facility];
    gate = prerequisite && !profile.facilities[prerequisite] ? `Open the ${names[prerequisite]} first.` :
      profile.shiftsCompleted < C.facilityShifts[facility]
        ? `Finish ${C.facilityShifts[facility]} ${C.facilityShifts[facility] === 1 ? 'shift' : 'shifts'} to unlock.` : '';
    descriptor = { id: requestedId, kind: 'facility', facility,
      label: count ? `${names[facility][0].toUpperCase()}${names[facility].slice(1)} open` : `Open ${names[facility]}`,
      price: count ? null : C.facilityPrices[facility], count, max: 1, maxed: !!count,
      requiredShifts: C.facilityShifts[facility], prerequisite: prerequisite ?? null };
  } else {
    const count = profile.chefLevel;
    gate = profile.facilities.restaurant ? '' : 'Open the ramen restaurant first.';
    descriptor = { id: 'chef-1', kind: 'chef', label: count ? 'Chef hired' : 'Hire better chef',
      price: count ? null : C.chefPrice, count, max: C.maxChefLevel, maxed: !!count, prerequisite: 'restaurant' };
  }
  const reason = profile.activeShift ? 'Finish the shift first.' : stale ? 'This offer is out of date.' :
    descriptor.maxed ? 'Already fully upgraded.' : gate ||
    (profile.bank < descriptor.price ? `Need ${descriptor.price - profile.bank} more coins.` : '');
  const code = profile.activeShift ? 'active-shift' : stale ? 'stale-offer' : descriptor.maxed ? 'maxed' :
    gate ? 'locked' : reason ? 'insufficient-funds' : null;
  return { ...descriptor, ok: !reason, enabled: !reason, reason, message: reason, ...(code ? { code } : {}) };
}

/** Earned, between-shift content upgrades; the legacy three-offer shop stays unchanged. */
export function contentOffers(profile) {
  if (!validProfile(profile)) return [];
  return [
    ...Array.from({ length: profile.openRooms }, (_, i) =>
      contentOffer(profile, `room-tier-${i + 1}-${Math.min(C.maxRoomTier, profile.roomTiers[i] + 1)}`)),
    ...facilityKinds.map(facility => contentOffer(profile, `facility-${facility}-1`)),
    ...(profile.restaurantTier ? [cuisineOffer(profile, `cuisine-${Math.min(C.maxRestaurantTier, profile.restaurantTier + 1)}`)] : []),
    contentOffer(profile, 'chef-1'),
  ];
}

function leisureOffer(profile, requestedId) {
  if (!validProfile(profile)) return { ...fail('Hotel save is invalid.', 'invalid-profile'),
    id: requestedId, label: '', price: null, enabled: false, maxed: false };
  const singer = requestedId === 'performer-1', venueId = singer ? null : requestedId.split('-')[1];
  const spec = singer ? PERFORMERS[1] : leisureById(venueId);
  const count = singer ? profile.performerLevel : profile.leisure[venueId];
  const prerequisite = singer ? 'theater' : venueId === 'lounge' ? 'pizza' : 'lounge';
  const earned = prerequisite === 'pizza' ? profile.restaurantTier === 6 : profile.leisure[prerequisite] === 1;
  const gate = !earned ? `Open ${prerequisite === 'pizza' ? 'the pizzeria' : `the ${prerequisite}`} first.`
    : profile.shiftsCompleted < spec.requiredShifts ? `Complete ${spec.requiredShifts} ${spec.requiredShifts===1?'shift':'shifts'} to unlock.` : '';
  const reason = profile.activeShift ? 'Finish the shift first.' : count ? 'Already fully upgraded.' : gate ||
    (profile.bank < spec.price ? `Need ${spec.price - profile.bank} more coins.` : '');
  const code = profile.activeShift ? 'active-shift' : count ? 'maxed' : gate ? 'locked' : reason ? 'insufficient-funds' : null;
  return { id: requestedId, kind: singer ? 'performer' : 'leisure', ...(singer ? { performerId: spec.id } : { venueId }),
    label: singer ? (count ? 'Star singer hired' : 'Hire star singer') : (count ? `${spec.name} open` : `Open ${spec.name.toLowerCase()}`),
    price: count ? null : spec.price, count, max: 1, maxed: !!count, prerequisite, requiredShifts: spec.requiredShifts,
    ok: !reason, enabled: !reason, reason, message: reason, ...(code ? { code } : {}) };
}
/** Kept separate so legacy room/facility menus retain their existing shape. */
export function leisureOffers(profile) {
  if (!validProfile(profile)) return [];
  return [...LEISURE_VENUES.map(venue => leisureOffer(profile, `leisure-${venue.id}-1`)), leisureOffer(profile, 'performer-1')];
}

