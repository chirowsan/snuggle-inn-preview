const C = ECONOMY_CONFIG, MAX = Number.MAX_SAFE_INTEGER;
const kinds = ['room', 'staff', 'service'];
const facilityKinds = ['restaurant', 'salon', 'spa'];
const object = value => value !== null && typeof value === 'object' && !Array.isArray(value);
// Saved JSON is untrusted. Ignore inherited fields, accessors and unknown keys.
const own = (value, key) => object(value) ? Object.getOwnPropertyDescriptor(value, key)?.value : undefined;
const integer = value => Number.isSafeInteger(value) && value >= 0;
const number = (value, fallback, min = 0, max = MAX) =>
  Number.isFinite(value) ? Math.min(max, Math.max(min, Math.floor(value))) : fallback;
const ordinal = id => {
  if (typeof id !== 'string' || !/^shift-[1-9]\d*$/.test(id)) return 0;
  const n = Number(id.slice(6));
  return Number.isSafeInteger(n) && n > 0 && `shift-${n}` === id ? n : 0;
};
const fail = (reason, code) => ({ ok: false, reason, message: reason, code });
const arrayItem = (value, index) => Array.isArray(value) ? Object.getOwnPropertyDescriptor(value, String(index))?.value : undefined;
const boundedText = (value, max) => typeof value === 'string' && value.length > 0 && value.length <= max;
const bindingKeys = ['engineVersion', 'motionRules', 'motionMode'];
const hasField = (value, key) => object(value) && key in value;
const hasBinding = value => bindingKeys.some(key => hasField(value, key));
const validBinding = value => own(value, 'engineVersion') === 7 && validMotionRule(own(value, 'motionRules')) &&
  ['rush', 'relaxed'].includes(own(value, 'motionMode'));
// Keep malformed binding attempts visibly invalid, rather than stripping their
// tags and accidentally reopening the legacy settlement path after a reload.
function copyBinding(value) {
  return { engineVersion: own(value, 'engineVersion') === 7 ? 7 : null,
    motionRules: validMotionRule(own(value, 'motionRules')) ? own(value, 'motionRules') : null,
    motionMode: ['rush', 'relaxed'].includes(own(value, 'motionMode')) ? own(value, 'motionMode') : null };
}

function cleanFacilities(raw) {
  const restaurant = number(own(raw, 'restaurant'), 0, 0, 1);
  const salon = restaurant ? number(own(raw, 'salon'), 0, 0, 1) : 0;
  return { restaurant, salon, spa: salon ? number(own(raw, 'spa'), 0, 0, 1) : 0 };
}

// Reviews are copied from the simulation, never generated by the shop or receipt.
function cleanReview(raw, shiftId) {
  const guestId = own(raw, 'guestId'), guestName = own(raw, 'guestName');
  const customerType = own(raw, 'customerType'), stars = own(raw, 'stars');
  const phrase = own(raw, 'phrase'), icons = own(raw, 'icons');
  if (!ordinal(shiftId) || !boundedText(guestId, 32) || !/^guest-[1-9]\d*$/.test(guestId) ||
    !boundedText(guestName, 64) || !boundedText(customerType, 32) ||
    !Number.isInteger(stars) || stars < 1 || stars > 5 || !boundedText(phrase, 240) ||
    !Array.isArray(icons) || icons.length > 8) return null;
  const safeIcons = Array.from({ length: icons.length }, (_, i) => arrayItem(icons, i));
  if (safeIcons.some(icon => !boundedText(icon, 32))) return null;
  return { shiftId, guestId, guestName, customerType, stars, icons: safeIcons, phrase };
}

function cleanReviews(raw, lastSettledShift, shiftId = null) {
  if (!Array.isArray(raw)) return [];
  const reviews = [], seen = new Set();
  // A shift has at most 100 guests. Bound work on malformed external saves too.
  for (let i = Math.max(0, raw.length - 100); i < raw.length; i++) {
    const entry = arrayItem(raw, i);
    const review = cleanReview(entry, shiftId ?? own(entry, 'shiftId'));
    if (!review || ordinal(review.shiftId) > lastSettledShift) continue;
    const key = `${review.shiftId}:${review.guestId}`;
    if (seen.has(key)) continue;
    seen.add(key); reviews.push(review);
  }
  return reviews.slice(-C.maxReviews);
}

function shiftReviews(raw, shiftId, lastSettledShift) {
  const direct = own(raw, 'reviews'), resultReviews = own(own(raw, 'result'), 'reviews');
  if (Array.isArray(direct) || Array.isArray(resultReviews))
    return cleanReviews(Array.isArray(direct) ? direct : resultReviews, lastSettledShift, shiftId);
  const guests = own(raw, 'guests');
  if (!Array.isArray(guests)) return [];
  const reviews = [];
  for (let i = 0; i < Math.min(guests.length, 100); i++) {
    const guest = arrayItem(guests, i), review = own(guest, 'review');
    if (!object(review) || !(own(guest, 'paid') === true || own(guest, 'abandoned') === true)) continue;
    reviews.push({ guestId: own(guest, 'id'), guestName: own(guest, 'name'),
      customerType: own(guest, 'customerType'), stars: own(review, 'stars'),
      icons: own(review, 'icons'), phrase: own(review, 'phrase') });
  }
  return cleanReviews(reviews, lastSettledShift, shiftId);
}

function cleanResult(raw, lastSettledShift) {
  const shiftId = own(raw, 'shiftId'), n = ordinal(shiftId), status = own(raw, 'status');
  if (!n || n !== lastSettledShift || !['won', 'lost', 'abandoned'].includes(status)) return null;
  const fields = ['startingBank', 'bank', 'earnings', 'costs', 'stolen', 'tips', 'completed', 'missed'];
  if (fields.some(key => !integer(own(raw, key)))) return null;
  const result = { shiftId, status, won: status === 'won' };
  for (const key of fields) result[key] = own(raw, key);
  if(Object.hasOwn(raw,'coinCash')){if(!validCoinCash(raw.coinCash))return null;result.coinCash={...raw.coinCash};}
  const exactNet=BigInt(result.earnings)-BigInt(result.costs)-BigInt(result.stolen)+BigInt(result.coinCash?.carried||0)-BigInt(result.coinCash?.held||0),net=Number(exactNet);
  if (!Number.isSafeInteger(net) || BigInt(result.startingBank)+exactNet !== BigInt(result.bank) || result.tips > result.earnings) return null;
  return { ...result, net };
}

/** Create an independent canonical profile; only whitelisted, finite data survives. */
export function createProfile(raw = null) {
  const bank = number(own(raw, 'bank'), C.startingBank);
  const openRooms = number(own(raw, 'openRooms'), C.startingRooms, 1, C.maxRooms);
  const facilities = cleanFacilities(own(raw, 'facilities'));
  // Never turn a malformed tier into a free top-level restaurant. Existing
  // restaurants with no cuisine data migrate to ramen, with every other asset intact.
  const rawTier = own(raw, 'restaurantTier');
  const restaurantTier = facilities.restaurant
    ? (integer(rawTier) && rawTier >= 1 && rawTier <= C.maxRestaurantTier ? rawTier : 1) : 0;
  const selected = cuisineById(own(raw, 'selectedCuisine'));
  const selectedCuisine = restaurantTier ? (selected && selected.tier <= restaurantTier ? selected.id : 'ramen') : null;
  const lastSettledShift = number(own(raw, 'lastSettledShift'), 0, 0, MAX - 1);
  const lastResult = cleanResult(own(raw, 'lastResult'), lastSettledShift);
  const shiftsCompleted = number(own(raw, 'shiftsCompleted'), 0);
  // Old profiles never acquire a venue or performer through future/stray keys.
  const rawLeisure = own(raw, 'version') === 4 ? own(raw, 'leisure') : null;
  const lounge = restaurantTier === 6 && shiftsCompleted >= 7 && own(rawLeisure, 'lounge') === 1 ? 1 : 0;
  const theater = lounge && shiftsCompleted >= 9 && own(rawLeisure, 'theater') === 1 ? 1 : 0;
  const performerLevel = theater && shiftsCompleted >= 10 && own(raw, 'version') === 4 && own(raw, 'performerLevel') === 1 ? 1 : 0;
  const rawActive = own(raw, 'activeShift'), activeId = own(rawActive, 'id');
  const activeOrdinal = ordinal(activeId), startingBank = own(rawActive, 'startingBank');
  const activeShift = activeOrdinal > lastSettledShift && activeOrdinal < MAX &&
    integer(startingBank) && startingBank === bank
    ? { id: activeId, ordinal: activeOrdinal, startingBank,
      ...(hasField(rawActive,'roomDoorXs')?{roomDoorXs:copyRoomDoorXs(own(rawActive,'roomDoorXs'))}:{}),
      ...(own(rawActive,'staffPlan')!==undefined?{staffPlan:copyStaffPlan(own(rawActive,'staffPlan'))}:{}),
      ...(hasBinding(rawActive) ? copyBinding(rawActive) : {}),
      ...(own(rawActive,'coinPickupRules')!==undefined?{coinPickupRules:own(rawActive,'coinPickupRules'),pickupCarry:copyDoorCoins(own(rawActive,'pickupCarry'))}:{}),
      ...(own(rawActive,'firstStepsRules')!==undefined?{firstStepsRules:own(rawActive,'firstStepsRules')}:{}),
      ...(own(rawActive,'reputationPlan')!==undefined?{reputationPlan:copyReputationPlan(own(rawActive,'reputationPlan'))}: {}) } : null;
  // Even a stale/invalid active entry cannot recycle a previously issued ID.
  const nextShift = Math.max(number(own(raw, 'nextShift'), 1, 1, MAX),
    lastSettledShift + 1, Math.min(MAX, activeOrdinal + 1));
  return {
    version: C.version, bank,
    ...(own(raw,'doorCoins')!==undefined?{doorCoins:copyDoorCoins(own(raw,'doorCoins'))}:{}),
    ...(own(raw,'firstSteps')!==undefined?{firstSteps:copyFirstSteps(own(raw,'firstSteps'))}:{}),
    ...(own(raw,'staffAutomation')!==undefined?{staffAutomation:copyStaffPlan(own(raw,'staffAutomation'))}:{}),
    rewards: own(raw,'rewards')!==undefined ? copyRewards(own(raw,'rewards')) : freshRewards(!object(raw)||Object.getOwnPropertyNames(raw).length===0),
    ...(own(raw,'location') !== undefined ? {location:copyLocation(own(raw,'location'))} : {}),
    ...(own(raw, 'construction') !== undefined ? {construction: copyConstruction(own(raw, 'construction'),openRooms)} : {}),
    ...(own(raw,'reputation')!==undefined?{reputation:copyReputation(own(raw,'reputation'))}:{}),
    openRooms,
    staffCount: number(own(raw, 'staffCount'), C.startingStaff, C.startingStaff, C.maxStaff),
    serviceLevel: number(own(raw, 'serviceLevel'), 0, 0, C.maxServiceLevel),
    roomTiers: Array.from({ length: C.maxRooms }, (_, i) => i < openRooms
      ? number(arrayItem(own(raw, 'roomTiers'), i), 0, 0, C.maxRoomTier) : 0),
    facilities, restaurantTier, selectedCuisine, leisure: { lounge, theater }, performerLevel,
    chefLevel: facilities.restaurant ? number(own(raw, 'chefLevel'), 0, 0, C.maxChefLevel) : 0,
    recentReviews: cleanReviews(own(raw, 'recentReviews'), lastSettledShift),
    nextShift, lastSettledShift,
    shiftsCompleted,
    guestsCompleted: number(own(raw, 'guestsCompleted'), 0),
    activeShift,
    lastResult,
  };
}

